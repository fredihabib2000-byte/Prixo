-- PRIXO ESL Manager — PostgreSQL / Supabase schema
--
-- One shared database for all customers. Every tenant-owned table carries a
-- tenant_id (= clients.id) and the foreign keys are composite, so a row can
-- never point at another tenant's store/product.
--
-- This file is idempotent: the app runs it on startup, and you can also paste
-- it into the Supabase SQL editor.

-- ---------------------------------------------------------------- central --
CREATE TABLE IF NOT EXISTS superadmins (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS clients (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug          TEXT NOT NULL UNIQUE,
    company_name  TEXT NOT NULL,
    city          TEXT,
    contact_email TEXT,
    contact_phone TEXT,
    plan          TEXT NOT NULL DEFAULT 'basic',
    license_key   TEXT NOT NULL UNIQUE,
    status        TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
    expires_at    TIMESTAMPTZ NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    notes         TEXT NOT NULL DEFAULT ''
);

-- ----------------------------------------------------------------- tenant --
CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    username      TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role          TEXT NOT NULL DEFAULT 'manager',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, username)
);

CREATE TABLE IF NOT EXISTS stores (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    name      TEXT NOT NULL,
    city      TEXT,
    status    TEXT NOT NULL DEFAULT 'active',
    UNIQUE (tenant_id, id)
);

CREATE TABLE IF NOT EXISTS products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    sku         TEXT NOT NULL,
    barcode     TEXT,
    name        TEXT NOT NULL,
    category    TEXT,
    price       NUMERIC(12,2) NOT NULL,
    promo_price NUMERIC(12,2),
    store_id    BIGINT,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, sku),
    UNIQUE (tenant_id, id),
    FOREIGN KEY (tenant_id, store_id) REFERENCES stores (tenant_id, id)
);

CREATE TABLE IF NOT EXISTS gateways (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    gateway_id TEXT NOT NULL,
    store_id   BIGINT,
    model      TEXT,
    ip_address TEXT,
    status     TEXT NOT NULL DEFAULT 'offline',
    last_seen  TIMESTAMPTZ,
    UNIQUE (tenant_id, gateway_id),
    FOREIGN KEY (tenant_id, store_id) REFERENCES stores (tenant_id, id)
);

CREATE TABLE IF NOT EXISTS labels (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    label_id    TEXT NOT NULL,
    model       TEXT,
    gateway_id  TEXT,
    status      TEXT NOT NULL DEFAULT 'offline',
    battery     INTEGER NOT NULL DEFAULT 100,
    signal      INTEGER NOT NULL DEFAULT 0,
    product_id  BIGINT,
    last_update TIMESTAMPTZ,
    UNIQUE (tenant_id, label_id),
    FOREIGN KEY (tenant_id, product_id) REFERENCES products (tenant_id, id)
);

CREATE TABLE IF NOT EXISTS updates (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    label_id   TEXT,
    sku        TEXT,
    old_price  NUMERIC(12,2),
    new_price  NUMERIC(12,2),
    status     TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Indexes on the composite foreign keys and the hot per-tenant queries
CREATE INDEX IF NOT EXISTS idx_stores_tenant        ON stores   (tenant_id);
CREATE INDEX IF NOT EXISTS idx_products_store       ON products (tenant_id, store_id);
CREATE INDEX IF NOT EXISTS idx_gateways_store       ON gateways (tenant_id, store_id);
CREATE INDEX IF NOT EXISTS idx_labels_product       ON labels   (tenant_id, product_id);
CREATE INDEX IF NOT EXISTS idx_labels_status        ON labels   (tenant_id, status);
CREATE INDEX IF NOT EXISTS idx_updates_tenant_id    ON updates  (tenant_id, id DESC);

-- --------------------------------------------------------------- security --
-- The app connects with the database owner role (which bypasses RLS). Turning
-- RLS on with NO policies, and revoking the public API roles, guarantees these
-- tables can never be read through Supabase's auto-generated REST/GraphQL API
-- with the public "anon" key.
DO $$
DECLARE
    t text;
    r text;
BEGIN
    FOREACH t IN ARRAY ARRAY['superadmins','clients','users','stores','products','gateways','labels','updates']
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        FOREACH r IN ARRAY ARRAY['anon','authenticated']
        LOOP
            IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
                EXECUTE format('REVOKE ALL ON TABLE %I FROM %I', t, r);
            END IF;
        END LOOP;
    END LOOP;
END
$$;
